export function getComboFeedback(comboCount: number): ComboFeedback | null {
  if (comboCount < 2) return null;
  const match = [...COMBO_FEEDBACK_TIERS].reverse().find((t) => comboCount >= t.comboCount);
  return match || COMBO_FEEDBACK_TIERS[0];
}
